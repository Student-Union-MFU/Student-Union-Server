-- ============================================================
-- ลืมรหัสผ่าน — อีเมลของผู้ใช้ + ตั๋วรีเซ็ตรหัสผ่าน
--
-- ก่อนหน้านี้ทั้งระบบ WBW ไม่มีอีเมลของใครเลยสักที่ (wbw_user มีแค่ username /
-- password_hash / student_id) การกู้รหัสผ่านจึงทำได้ทางเดียวคือให้แอดมินตั้งใหม่ให้
-- ผ่าน /wbw/admin/users/{id}/password ซึ่งใช้ไม่ได้กับคนที่ลืมรหัสตอนตีสอง
--
-- สองบทบาทอยู่คนละสถานะกัน:
--   participant — username = student_id (บังคับ ^693\d{7}$) อีเมลมหาวิทยาลัยจึง
--                 "คำนวณได้" จาก student_id || '@lamduan.mfu.ac.th' เหมือนที่
--                 ไฟล์ส่งออกทะเบียนทำอยู่แล้ว (wbw_export_repository.go) — ไม่ต้อง
--                 backfill อะไรเลย ทุกคนที่สมัครไปแล้วรีเซ็ตได้ทันที
--   staff       — username เป็นข้อความอิสระ ไม่มี student_id ไม่มีอีเมล ต้องเริ่ม
--                 "ถาม" ตอนสมัคร (/wbw/auth/staff-register) นับจากนี้
--
-- คอลัมน์จึงเป็น NULL ได้: แถวเก่าของเจ้าหน้าที่ไม่มีอีเมลและจะไม่มีวันมี จนกว่า
-- เจ้าตัวจะแจ้ง — คนกลุ่มนี้ยังใช้ทางเดิม (แอดมินตั้งรหัสให้) ได้เหมือนเดิม
-- ปลายทางที่ใช้จริงจึงเป็น COALESCE(email, student_id || '@lamduan.mfu.ac.th')
-- ที่เดียว ไม่ใช่ if/else แยกตาม role ในโค้ด
-- ============================================================

ALTER TABLE wbw_user ADD COLUMN email TEXT;

-- ยูนีคแบบไม่สนตัวพิมพ์ และเฉพาะแถวที่กรอกมา — NULL ซ้ำกันได้ (เจ้าหน้าที่เก่าทุกคน
-- เป็น NULL) แต่ห้ามสองบัญชีถืออีเมลเดียวกัน ไม่งั้นลิงก์รีเซ็ตใบเดียวอาจตรงกับ
-- หลายบัญชีจนไม่รู้ว่าใครเป็นเจ้าของ
CREATE UNIQUE INDEX wbw_user_email_key ON wbw_user (lower(email)) WHERE email IS NOT NULL;

-- ------------------------------------------------------------
-- ตั๋วรีเซ็ตรหัสผ่าน
--
-- เก็บ "แฮชของ token" ไม่ใช่ token — token ตัวจริงอยู่ในอีเมลของเจ้าตัวเท่านั้น
-- คนที่อ่านตารางนี้ได้ (dump, backup, สิทธิ์อ่านฐาน) จึงเอาไปตั้งรหัสผ่านใหม่ของ
-- คนอื่นไม่ได้ · sha256 พอ ไม่ต้อง bcrypt เพราะ token เป็นสุ่ม 256 บิตอยู่แล้ว
-- ไม่มีอะไรให้เดา (ต่างจากรหัสผ่านที่คนตั้งเอง)
--
-- used_at แทนการลบทิ้ง: แถวที่ใช้แล้วยังต้องอยู่ให้การนับ rate limit เห็น ไม่งั้น
-- ขอลิงก์ใหม่ → กดใช้ → ขอใหม่ วนไปเรื่อย ๆ ได้ไม่จำกัดเพราะแถวหายทุกรอบ
-- ------------------------------------------------------------
CREATE TABLE wbw_password_reset (
  token_hash BYTEA PRIMARY KEY,
  user_id    UUID NOT NULL REFERENCES wbw_user(user_id) ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at    TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ใช้สองทาง: นับใบที่ขอไปเมื่อชั่วโมงที่แล้ว (rate limit) และล้างใบเก่าของคนเดิม
-- ตอนตั้งรหัสสำเร็จ
CREATE INDEX wbw_password_reset_user_idx ON wbw_password_reset (user_id, created_at DESC);
